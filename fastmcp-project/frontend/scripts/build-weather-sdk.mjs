import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const outputDirectory = resolve(root, '../tools/weather/vendor');
const packages = ['@modelcontextprotocol/ext-apps', '@modelcontextprotocol/sdk', 'zod'];

async function packageLicense(name) {
  const directory = resolve(root, 'node_modules', name);
  const manifest = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8'));
  const license = await readFile(resolve(directory, 'LICENSE'), 'utf8');
  return `${name}@${manifest.version}\n${license}`;
}

const licenses = await Promise.all(packages.map(packageLicense));
const bundle = await build({
  stdin: {
    contents: 'export { App } from "@modelcontextprotocol/ext-apps";',
    resolveDir: root,
    sourcefile: 'weather-sdk-entry.js',
  },
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'WeatherAppSDK',
  platform: 'browser',
  minify: true,
  legalComments: 'inline',
  banner: { js: `/*! Generated by npm run build:sdk. Do not edit.\n${licenses.join('\n\n')}\n*/` },
});

// 产物将被内联到 HTML 的 module script，避免字符串意外结束 script 标签。
const source = bundle.outputFiles[0].text.replaceAll(/<\/script/gi, '<\\/script');
await mkdir(outputDirectory, { recursive: true });
await writeFile(resolve(outputDirectory, 'weather-app-sdk.js'), source, 'utf8');
console.log('Local MCP Apps SDK generated: tools/weather/vendor/weather-app-sdk.js');
